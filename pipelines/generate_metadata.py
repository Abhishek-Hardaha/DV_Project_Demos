def build_all_metadata():
    print("=== Generating Structured Registries ===")
    
    SHOWCASE_RANKS = {
        "D01": 1,
        "D02": 2,
        "D06": 3,
        "D11": 4,
        "D12": 5,
        "D17": 6,
        "D18": 7,
        "D28": 8,
        "D29": 9,
        "D33": 10
    }
    MAP_DASHBOARDS = {"D11", "D28"}
    for cfg in DASHBOARDS_CONFIG:
        did = cfg["id"]
        cfg["is_showcase"] = did in SHOWCASE_RANKS
        cfg["showcase_rank"] = SHOWCASE_RANKS.get(did, None)
        cfg["has_map"] = did in MAP_DASHBOARDS
        cfg["visual_count"] = 13

    # 1. Dashboards Registry
    dash_path = os.path.join(META_DIR, "dashboards.json")
    with open(dash_path, "w", encoding="utf-8") as f:
        json.dump(DASHBOARDS_CONFIG, f, indent=2)
    print(f"Saved Dashboards Registry ({len(DASHBOARDS_CONFIG)} dashboards) -> {dash_path}")

    # 2. Datasets Registry
    datasets = []
    for cfg in DASHBOARDS_CONFIG:
        csv_path = os.path.join(BASE_DIR, "data", "analytical", f"{cfg['slug']}.csv")
        row_c, col_c = 0, 0
        if os.path.exists(csv_path):
            df = pd.read_csv(csv_path)
            row_c, col_c = len(df), len(df.columns)
        datasets.append({
            "dataset_id": cfg["slug"],
            "dashboard_id": cfg["id"],
            "title": cfg["title"],
            "domain": cfg["domain"],
            "source_organization": cfg["source_org"],
            "source_url": cfg["source_url"],
            "raw_path": f"data/raw/{cfg['slug']}_raw.csv",
            "analytical_csv_path": f"data/analytical/{cfg['slug']}.csv",
            "analytical_parquet_path": f"data/analytical/{cfg['slug']}.parquet",
            "row_count": row_c,
            "column_count": col_c,
            "temporal_coverage": cfg["date_range"],
            "geographic_coverage": cfg["geographic_scope"],
            "refresh_status": cfg["refresh_status"]
        })
    data_path = os.path.join(META_DIR, "datasets.json")
    with open(data_path, "w", encoding="utf-8") as f:
        json.dump(datasets, f, indent=2)
    print(f"Saved Datasets Registry ({len(datasets)} datasets) -> {data_path}")

    # 3. Sources Registry
    sources = generate_sources()
    src_path = os.path.join(META_DIR, "sources.json")
    with open(src_path, "w", encoding="utf-8") as f:
        json.dump(sources, f, indent=2)
    print(f"Saved Sources Registry ({len(sources)} organizations) -> {src_path}")

    # 4. APIs Registry
    apis = generate_apis()
    api_path = os.path.join(META_DIR, "apis.json")
    with open(api_path, "w", encoding="utf-8") as f:
        json.dump(apis, f, indent=2)
    print(f"Saved APIs Registry ({len(apis)} API endpoints) -> {api_path}")

    # 5. Power BI Readiness Models
    pbi_models = generate_powerbi_models()
    pbi_path = os.path.join(PBI_DIR, "powerbi_models.json")
    with open(pbi_path, "w", encoding="utf-8") as f:
        json.dump(pbi_models, f, indent=2)
    print(f"Saved Power BI Readiness Models ({len(pbi_models)} models) -> {pbi_path}")

if __name__ == "__main__":
    build_all_metadata()
